# 辅助标签：不拿来定分类，只做加分项
EARNINGS = [
    "增长", "预增", "扭亏", "减亏", "业绩", "营收", "净利", "半年报", "三季报", "中报", "年报",
    "一季报", "高增", "大增", "预盈", "盈利", "改善", "扩大",
]


def is_earnings(tag):
    return any(k in tag for k in EARNINGS)


def map_tag(tag):
    """单个标签 -> 板块名 / None"""
    if not tag:
        return None
    # 「东方」这类纯名称
    if tag in ("东方", "东方系") or tag.startswith("东方+"):
        return "名称炒作"
    for cat, kws in RULES:
        for kw in kws:
            if kw in tag:
                return cat
    return None


def classify(reason):
    """
    涨停原因 -> 板块。
    按标签顺序找第一个能归类的；跳过业绩类辅助标签。
    """
    if not reason:
        return "其他概念", None
    tags = [p.strip().strip('“”"') for p in str(reason).split("+")]
    tags = [p for p in tags if p]

    # 「羊字辈」这类名字炒作优先——同花顺面板也是这么归的
    for t in tags:
        if "字辈" in t:
            return "名称炒作", t

    # 先按顺序匹配主概念（跳过业绩标签）
    for t in tags:
        if is_earnings(t):
            continue
        c = map_tag(t)
        if c:
            return c, t

    # 再放宽：业绩标签也可能带出板块（如「三季报增长」没有板块，跳过）
    for t in tags:
        c = map_tag(t)
        if c:
            return c, t

    return "其他概念", (tags[0] if tags else None)
